import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { equalEarth } from "../src/ui/world-map-projection";

type Ring = [number, number][];
type Feature = {
  properties: Record<string, string>;
  geometry:
    { type: "Polygon"; coordinates: Ring[] } | { type: "MultiPolygon"; coordinates: Ring[][] };
};

const source = process.argv[2];
if (!source)
  throw new Error(
    "Pass the Natural Earth 110m countries GeoJSON: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson"
  );

const root = path.resolve(import.meta.dirname, "..");
const width = 1000;
const pad = 4;
const tolerance = 0.9;
const features: Feature[] = JSON.parse(readFileSync(source, "utf8")).features.filter(
  (feature: Feature) => feature.properties.ISO_A3 !== "ATA"
);
const polygons = (feature: Feature) =>
  feature.geometry.type === "Polygon"
    ? [feature.geometry.coordinates]
    : feature.geometry.coordinates;

const unit = features.map((feature) =>
  polygons(feature).map((polygon) =>
    polygon.map((ring) => ring.map(([lng, lat]) => equalEarth(lng, lat)))
  )
);
const all = unit.flat(3);
const minX = Math.min(...all.map(([x]) => x));
const maxX = Math.max(...all.map(([x]) => x));
const minY = Math.min(...all.map(([, y]) => y));
const maxY = Math.max(...all.map(([, y]) => y));
const scale = (width - pad * 2) / (maxX - minX);
const height = Math.ceil((maxY - minY) * scale + pad * 2);
const round = (value: number) => Math.round(value * 10) / 10;
const toView = ([x, y]: [number, number]): [number, number] => [
  round((x - minX) * scale + pad),
  round((maxY - y) * scale + pad)
];

const distance = (
  [ax, ay]: [number, number],
  [bx, by]: [number, number],
  [px, py]: [number, number]
) => {
  const dx = bx - ax;
  const dy = by - ay;
  const length = dx * dx + dy * dy;
  const t = length ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / length)) : 0;
  return Math.hypot(px - ax - t * dx, py - ay - t * dy);
};
const simplify = (points: [number, number][]): [number, number][] => {
  if (points.length < 3) return points;
  let index = 0;
  let furthest = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = distance(points[0], points.at(-1)!, points[i]);
    if (d > furthest) [index, furthest] = [i, d];
  }
  if (furthest <= tolerance) return [points[0], points.at(-1)!];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
};
const number = (value: number) => String(value).replace(/^(-?)0\./, "$1.");
const pair = (x: number, y: number) => number(x) + (y < 0 ? "" : " ") + number(y);
const ringPath = (ring: [number, number][]) => {
  const points = simplify(ring.map(toView));
  if (points.length < 4) return "";
  let [x, y] = points[0];
  let d = "M" + pair(x, y) + "l";
  points.slice(1, -1).forEach(([nx, ny], index) => {
    const step = pair(round(nx - x), round(ny - y));
    d += (index && !step.startsWith("-") ? " " : "") + step;
    [x, y] = [nx, ny];
  });
  return d + "z";
};

const countries = features
  .map((feature, index) => {
    const code = feature.properties.ISO_A2_EH;
    const d = unit[index].flatMap((polygon) => polygon.map(ringPath)).join("");
    return [code === "-99" ? "" : code, d] as const;
  })
  .filter(([, d]) => d)
  .sort(([a], [b]) => a.localeCompare(b));

const frame = {
  width,
  height,
  scale: round(scale * 1000) / 1000,
  x: round(pad - minX * scale),
  y: round(pad + maxY * scale)
};
const output = `/* Generated by scripts/world-map.ts from Natural Earth 110m admin 0 countries (public domain), Antarctica left out, Equal Earth projection. */
export const worldMapFrame = ${JSON.stringify(frame)};

/** [ISO 3166-1 alpha-2 code, SVG path]. The code is empty for areas without one. */
export const worldMapCountries: [string, string][] = [
${countries.map((country) => "  " + JSON.stringify(country)).join(",\n")}
];
`;
writeFileSync(path.join(root, "src/ui/world-map-geometry.ts"), output);
console.log(`${countries.length} countries, ${output.length} bytes, ${width}x${height}`);
